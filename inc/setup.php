/**
 * Idempotent site setup / scaffolding.
 *
 * Creates the pages the theme references (Privacy, Terms, Accessibility). Two
 * invariants, borrowed from a well-worn pattern: it NEVER overwrites and NEVER
 * deletes, so running it repeatedly is safe. No menus are created — navigation
 * is Page-driven (see Theme Options → Navigation).
 *
 * Runs once on theme activation, and is re-runnable from
 * Appearance → Theme Options → General → "Create anything missing" (upgrading
 * a theme in place does not fire the activation hook).
 *
 * @package Rodolfo
 */

if ( ! defined( 'ABSPATH' ) ) {
    exit;
}

/**
 * The pages the theme wants to exist. Keyed by canonical slug.
 *
 * Each entry carries the title, any alternate slugs that count as "this page
 * already exists" (so setup never creates a duplicate), and starter content.
 *
 * On content: FAQ and Accessibility ship genuinely useful skeletons. Privacy
 * and Terms deliberately ship a clearly-marked outline rather than real legal
 * copy — that text is jurisdiction-specific and a theme is the wrong place to
 * supply it. WordPress's own generator at Settings → Privacy produces a proper
 * Privacy Policy draft; the placeholder points there.
 */
function rodolfo_setup_pages() {
    return array(
        'faq'            => array(
            'title'   => __( 'FAQ', 'rodolfo' ),
            'aliases' => array( 'faqs', 'frequently-asked-questions' ),
            'content' => rodolfo_setup_content_faq(),
        ),
        'terms'          => array(
            'title'   => __( 'Terms of Use', 'rodolfo' ),
            'aliases' => array( 'terms-of-use', 'terms-and-conditions' ),
            'content' => rodolfo_setup_content_terms(),
        ),
        'privacy-policy' => array(
            'title'   => __( 'Privacy Policy', 'rodolfo' ),
            'aliases' => array( 'privacy' ),
            'content' => rodolfo_setup_content_privacy(),
        ),
        'accessibility'  => array(
            'title'   => __( 'Accessibility', 'rodolfo' ),
            'aliases' => array( 'accessibility-statement' ),
            'content' => rodolfo_setup_content_accessibility(),
        ),
    );
}

/**
 * Find an existing page for a setup entry, honouring alternate slugs.
 * Privacy additionally defers to the page registered in Settings → Privacy.
 */
function rodolfo_setup_find_page( $slug, $entry ) {
    if ( 'privacy-policy' === $slug && function_exists( 'rodolfo_privacy_page' ) ) {
        $page = rodolfo_privacy_page();
        if ( $page ) {
            return $page;
        }
    }
    $candidates = array_merge( array( $slug ), (array) $entry['aliases'] );
    foreach ( $candidates as $candidate ) {
        $page = get_page_by_path( $candidate );
        if ( $page ) {
            return $page;
        }
    }
    return null;
}

