/**
 * Report what exists vs. what is missing, without creating anything.
 * Returns array( slug => array( 'title', 'exists' => bool, 'id' => int|0 ) ).
 */
function rodolfo_setup_status() {
    $status = array();
    foreach ( rodolfo_setup_pages() as $slug => $entry ) {
        $page = rodolfo_setup_find_page( $slug, $entry );
        $status[ $slug ] = array(
            'title'  => $entry['title'],
            'exists' => (bool) $page,
            'id'     => $page ? (int) $page->ID : 0,
            'empty'  => $page ? ( '' === trim( (string) $page->post_content ) ) : false,
            'slug'   => $page ? $page->post_name : $slug,
        );
    }
    return $status;
}

/**
 * Create only what is absent. Never overwrites content, never deletes.
 * Returns a list of human-readable strings describing what was created.
 */
function rodolfo_setup_run() {
    $created  = array();
    $page_ids = array();

    foreach ( rodolfo_setup_pages() as $slug => $entry ) {
        $existing = rodolfo_setup_find_page( $slug, $entry );
        if ( $existing ) {
            $page_ids[ $slug ] = (int) $existing->ID;

            // Backfill starter content into a page that exists but is empty.
            // Pages created before 2.12.0 were inserted blank, and the loop
            // used to skip them forever — so "Create anything missing" could
            // never fix them. Filling an empty page destroys nothing, and the
            // never-overwrite guarantee still holds for pages with real
            // content: anything non-empty is left strictly alone.
            if ( '' === trim( (string) $existing->post_content ) && '' !== $entry['content'] ) {
                $updated_id = wp_update_post( array(
                    'ID'           => (int) $existing->ID,
                    'post_content' => $entry['content'],
                ), true );
                if ( $updated_id && ! is_wp_error( $updated_id ) ) {
                    /* translators: %s: page title */
                    $created[] = sprintf( __( 'Added starter content to empty page: %s', 'rodolfo' ), $entry['title'] );
                }
            }
            continue;
        }
        $id = wp_insert_post( array(
            'post_title'   => $entry['title'],
            'post_name'    => $slug,
            'post_status'  => 'publish',
            'post_type'    => 'page',
            'post_content' => $entry['content'],
        ) );
        if ( $id && ! is_wp_error( $id ) ) {
            $page_ids[ $slug ] = (int) $id;
            /* translators: %s: page title */
            $created[] = sprintf( __( 'Created page: %s', 'rodolfo' ), $entry['title'] );
        }
    }

    // Register the WordPress privacy page so Settings → Privacy is wired up.
    if ( ! empty( $page_ids['privacy-policy'] ) && ! (int) get_option( 'wp_page_for_privacy_policy' ) ) {
        update_option( 'wp_page_for_privacy_policy', $page_ids['privacy-policy'] );
    }

    // Terms & Accessibility are ordinary Pages: they appear automatically in the
    // primary nav (Theme Options → Navigation can move any page to the footer),
    // so setup no longer wires footer URL options for them.

    return $created;
}

/**
 * Activation hook — scaffold on first switch to the theme.
 */
function rodolfo_setup_on_activation() {
    rodolfo_setup_run();
    flush_rewrite_rules();
}
add_action( 'after_switch_theme', 'rodolfo_setup_on_activation' );

/**
 * Handle the "Create anything missing" button from Theme Options.
 */
function rodolfo_setup_handle() {
    if ( ! current_user_can( 'manage_options' ) ) {
        wp_die( esc_html__( 'Insufficient permissions.', 'rodolfo' ) );
    }
    check_admin_referer( 'rodolfo_run_setup' );
    $created = rodolfo_setup_run();
    flush_rewrite_rules();
    $notice = empty( $created ) ? 'setup_nothing' : 'setup_ok';
    wp_safe_redirect( add_query_arg(
        array( 'rodolfo_notice' => $notice, 'tab' => 'general' ),
        admin_url( 'themes.php?page=rodolfo-theme-options' )
    ) );
    exit;
}
add_action( 'admin_post_rodolfo_run_setup', 'rodolfo_setup_handle' );
